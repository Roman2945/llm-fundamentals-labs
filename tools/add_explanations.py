def main(root="."):
    for rel, notes in FILES.items():
        path = Path(root) / rel
        nb = json.loads(path.read_text(encoding="utf-8"))
        cells = nb["cells"]
        if any("".join(c["source"]).startswith(MARK) for c in cells):
            print("вже є пояснення:", rel)
            continue
        for idx in sorted(notes, reverse=True):
            assert cells[idx]["cell_type"] == "code", (rel, idx)
            cells.insert(idx, {"cell_type": "markdown", "metadata": {}, "source": [f"{MARK} {notes[idx]}"]})
        path.write_text(json.dumps(nb, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"{rel}: додано {len(notes)} пояснень")


if __name__ == "__main__":
    main(Path(__file__).resolve().parent.parent)
